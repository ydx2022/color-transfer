function glyphW(): number {
  return 5;
}
function glyphH(): number {
  return 7;
}

// 在 canvas 上以 (x,y) 为左上角绘制文字，返回占用宽度（像素，含字间距）。
export function drawText(
  c: Canvas,
  x: number,
  y: number,
  text: string,
  r: number,
  g: number,
  b: number,
  scale = 1,
  spacing = 1
): number {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g7 = FONT[ch] ?? FONT[" "];
    for (let row = 0; row < glyphH(); row++) {
      const bits = g7[row];
      for (let col = 0; col < glyphW(); col++) {
        if ((bits >> (glyphW() - 1 - col)) & 1) {
          for (let sy = 0; sy < scale; sy++) {
            for (let sx = 0; sx < scale; sx++) {
              setPx(c, cx + col * scale + sx, y + row * scale + sy, r, g, b);
            }
          }
        }
      }
    }
    cx += (glyphW() + spacing) * scale;
  }
  return cx - x;
}

// 居中绘制文字（基于 canvas 宽度）。
export function drawTextCentered(
  c: Canvas,
  cy: number,
  text: string,
  r: number,
  g: number,
  b: number,
  scale = 1,
  spacing = 1
): void {
  const w = text.length * (glyphW() + spacing) * scale;
  drawText(c, Math.max(0, Math.round((c.width - w) / 2)), cy, text, r, g, b, scale, spacing);
}
